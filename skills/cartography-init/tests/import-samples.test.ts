import { describe, expect, it } from "vitest";
import { createHash } from "node:crypto";
import { zipSync } from "fflate";
import { XMLParser } from "fast-xml-parser";
import { parseQgis } from "../src/adapters/qgis.js";
import { initializeCartography } from "../src/index.js";
import { verifyDocument } from "../src/verify.js";
import { loadFixture } from "./helpers.js";

const samples = [
  { file: "OSM Simple Light.lyrx", elements: 38, colors: 44, skipped: 0,
    evidence: ["#c2eaff", "#cbe7cb"] },
  { file: "style-example.sld", elements: 3, colors: 9, skipped: 3,
    evidence: ["#87CEEB", "#FFFACD", "#F08080"] },
  { file: "OS GeoDataViz Colours & Symbols (ArcPro)_v2.stylx", elements: 0, colors: 125, skipped: 0,
    evidence: ["rag-status-1:", "rag-status-cvd-3:", "#e9002d"] },
  { file: "style-v8.json", elements: 48, colors: 55, skipped: 46,
    evidence: ["hsl(47, 26%, 88%)", "hsl(205, 56%, 73%)"] },
] as const;

describe("user-supplied import samples", () => {
  it.each(samples)("converts $file into a valid draft with source evidence", sample => {
    const result = initializeCartography(loadFixture(`import-samples/${sample.file}`), sample.file, sample.file);
    expect(verifyDocument(result.source).ok).toBe(true);
    expect(Buffer.byteLength(result.source)).toBeLessThanOrEqual(64 * 1024);
    expect(JSON.parse(result.reportJson)).toMatchObject({
      statistics: { elements: sample.elements, colors: sample.colors, skipped: sample.skipped },
    });
    for (const evidence of sample.evidence) expect(result.source).toContain(evidence);
    if (sample.file.endsWith(".sld")) {
      expect(result.reportMarkdown).toContain("Categorize");
      expect(result.reportMarkdown).toContain("TextSymbolizer");
    }
    if (sample.file === "style-v8.json") {
      expect(result.reportJson).toContain("stops");
      expect(result.reportMarkdown).toContain("line-width");
    }
  });
});

const qgisSamples = [
  { file: "qgis-quickapp.qgs", sha256: "f1a7c68cdd5de3e5061f3e589db34893316a472ca85b10f7563315c1f8b84c3b",
    statistics: { elements: 4, colors: 6, skipped: 19 },
    evidence: ["#9a8b74", "rgba(118, 191, 227, 0.5176470588235295)", "0.66mm"],
    skipped: ["attr=Name", "SvgMarker", "line_style", "labelsEnabled=1"] },
  { file: "qgis-selective-masking.qgs", sha256: "b0a3f607a59ffaabc2f40ff9b083c91196bedba86975a7f3fb86a2f130ebdba1",
    statistics: { elements: 9, colors: 9, skipped: 61 },
    evidence: ["#ffff06", "#377eb8", "1.86mm", "16pt", "Sans"],
    skipped: ["多个 symbol layer", "MarkerLine", "SvgMarker", "text-mask", "规则式标注", "额外 text-style[1]", "textColor", "labelsEnabled=0", "栅格渲染器"] },
] as const;

describe("upstream QGIS project regression baselines", () => {
  it.each(qgisSamples)("pins the original bytes, full extraction and report for $file", sample => {
    const buffer = loadFixture(`import-samples/${sample.file}`);
    expect(createHash("sha256").update(buffer).digest("hex")).toBe(sample.sha256);
    const extracted = parseQgis(buffer, sample.file);
    const result = initializeCartography(buffer, sample.file, sample.file);
    const report = JSON.parse(result.reportJson);
    const baseline = JSON.parse(loadFixture(`import-samples/${sample.file}.baseline.json`).toString("utf8"));
    // Baselines are committed observations, never regenerated by the test.
    expect(JSON.parse(JSON.stringify(extracted))).toEqual(baseline.extracted);
    expect(report).toEqual(baseline.report);
    expect(createHash("sha256").update(result.source).digest("hex")).toBe(baseline.documentSha256);
    expect(verifyDocument(result.source)).toEqual({ ok: true, errors: [] });
    expect(Buffer.byteLength(result.source)).toBeLessThanOrEqual(64 * 1024);
    expect(report.statistics).toEqual(sample.statistics);
    for (const evidence of sample.evidence) expect(result.source).toContain(evidence);
    for (const reason of sample.skipped) {
      expect(extracted.skipped.some(item => item.reason.includes(reason)), `missing skipped reason: ${reason}`).toBe(true);
      expect(result.reportMarkdown).toContain(reason);
    }
    expect(extracted.skipped.every(item => item.detail === undefined || item.detail.length <= 200)).toBe(true);
  });

  it.each(qgisSamples)("imports the same real project through the QGZ archive path: $file", sample => {
    // This packaging check uses real QGS bytes; it is not an upstream QGZ fixture.
    const qgs = loadFixture(`import-samples/${sample.file}`);
    const qgz = Buffer.from(zipSync({ "项目/project.qgs": qgs, "project.qgd": new Uint8Array() }));
    const fileName = sample.file.replace(/\.qgs$/, ".qgz");
    expect(parseQgis(qgz, fileName)).toEqual({ ...parseQgis(qgs, sample.file), source: { kind: "qgis", name: fileName } });
    const direct = initializeCartography(qgs, sample.file, "QGIS regression");
    const archived = initializeCartography(qgz, fileName, "QGIS regression");
    expect(archived.source).toBe(direct.source);
    expect(JSON.parse(archived.reportJson)).toEqual({ ...JSON.parse(direct.reportJson), source: { kind: "qgis", name: fileName, file: fileName } });
  });

  it("verifies the upstream masking project actually contains the intended coverage", () => {
    const buffer = loadFixture("import-samples/qgis-selective-masking.qgs");
    const project = new XMLParser({ ignoreAttributes: false }).parse(buffer).qgis as {
      projectlayers: { maplayer: Array<{
        "renderer-v2"?: { "@_type": string; symbols?: { symbol?: { layer?: unknown } } };
        labeling?: { "@_type": string };
      }> };
    };
    const layers = project.projectlayers.maplayer;
    expect(layers.some(layer => layer["renderer-v2"]?.["@_type"] === "categorizedSymbol")).toBe(true);
    expect(layers.some(layer => layer.labeling?.["@_type"] === "rule-based")).toBe(true);
    expect(layers.some(layer => Array.isArray(layer["renderer-v2"]?.symbols?.symbol?.layer))).toBe(true);
    const ir = parseQgis(buffer, "qgis-selective-masking.qgs");
    expect(ir.elements.find(element => element.name === "lines_with_labels" && element.geometry === "line")?.style)
      .toEqual({ strokeColor: "#ffff06", strokeWidth: { value: 1.86, unit: "mm" } });
    expect(ir.typography[0]?.fontSize).toEqual({ value: 16, unit: "pt" });
  });
});
