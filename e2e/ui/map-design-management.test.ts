import { expect, test } from '@/playwright/suite';
import { createAndOpenReadyMapProject } from '@/playwright/map-design-project';

test('[P1] searches, renames, reopens and deletes a project through the library', async ({ page, toolsDev }) => {
  test.setTimeout(120_000);
  const title = `Project acceptance ${crypto.randomUUID()}`;
  const renamed = `${title} renamed`;
  const projectId = await createAndOpenReadyMapProject(page, toolsDev.daemonUrl!, { title });
  await page.getByRole('button', { name: 'Back to home', exact: true }).click();
  await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('button', { name: 'Map projects', exact: true }).click();
  const search = page.getByRole('searchbox', { name: 'Search projects', exact: true });
  await search.fill('no-match-for-acceptance');
  await expect(page.getByText('No matching projects', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Clear filters', exact: true }).click();
  await search.fill(title);
  await page.getByRole('button', { name: `More actions: ${title}`, exact: true }).click();
  await page.getByRole('button', { name: 'Rename', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('textbox', { name: 'Project name', exact: true }).fill(' ');
  await expect(dialog.getByRole('button', { name: 'Rename', exact: true })).toBeDisabled();
  await dialog.getByRole('textbox', { name: 'Project name', exact: true }).fill(renamed);
  await dialog.getByRole('button', { name: 'Rename', exact: true }).click();
  await expect(page.getByRole('button', { name: renamed, exact: true })).toBeVisible();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: renamed, exact: true }).click();
  await expect(page).toHaveURL(new RegExp(`/projects/${projectId}`));
  await expect(page.getByRole('heading', { name: renamed, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Back to home', exact: true }).click();
  await page.getByRole('button', { name: `More actions: ${renamed}`, exact: true }).click();
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('button', { name: renamed, exact: true })).toBeVisible();
  await page.getByRole('button', { name: `More actions: ${renamed}`, exact: true }).click();
  await page.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(page.getByRole('button', { name: renamed, exact: true })).toHaveCount(0);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('button', { name: renamed, exact: true })).toHaveCount(0);
});

test('[P1] saves settings and preserves language across reload and mobile navigation', async ({ page }) => {
  await page.goto('/settings', { waitUntil: 'domcontentloaded' });
  const instructions = page.getByRole('textbox', { name: 'Custom instructions', exact: true });
  await instructions.fill('Keep labels legible — settings acceptance.');
  await page.getByRole('button', { name: 'Save settings', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Settings saved' })).toBeVisible();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(instructions).toHaveValue('Keep labels legible — settings acceptance.');
  await page.getByRole('navigation', { name: 'Primary navigation' }).getByRole('button', { name: 'Language & appearance', exact: true }).click();
  await page.getByRole('combobox', { name: 'Language', exact: true }).click();
  await page.getByRole('option', { name: '简体中文', exact: true }).click();
  await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await expect(page.getByRole('heading', { name: '设置', exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '打开导航', exact: true }).click();
  await page.getByRole('navigation').getByRole('button', { name: '返回主界面', exact: true }).click();
  await expect(page).toHaveURL(/\/$/);
  await expect(page.getByRole('dialog')).toHaveCount(0);
});
